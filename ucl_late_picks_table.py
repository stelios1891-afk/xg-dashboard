# -*- coding: utf-8 -*-
"""ucl_late_picks_table.py — CHAMPIONS LEAGUE: PICKS ΠΟΥ ΔΕΝ ΥΠΗΡΧΑΝ ΑΠΟ ΤΗΝ ΑΡΧΗ (13/10/2026, Στελιος: «θελω να δω πως αποδιδουν τα picks
χαντικαπ και συνολων που δεν βγαινουν απο την αρχη, αλλα 48, 36, 24, 12, 8, 4, 2 ωρες … και επειδη συνηθως βγαινουν μετα απο κοντρα, αν
υπαρχει καποια κοντρα και πανω που ειναι καταστροφικη οπως ο κανονας Γ της Ευρωλιγκας, και αν η κοντρα τους συνεχιζεται μεχρι το κλεισιμο»).
Πηγη: ucl_bb_timing_alerts.pkl (σημερινοι κανονες, ΚΑΘΕ αλλαγη τιμης ≤72ω, Crown & SBOBET — μεσος ορος). «Απο την αρχη» = ηδη pick στις 72ω.
Πινακας 1: ανα ωρα ΠΡΩΤΗΣ εμφανισης (μονο οσα ΔΕΝ ηταν απο την αρχη) — ROI στην εισοδο / στο κλεισιμο, κοντρα ΠΡΙΝ, κινηση ΜΕΤΑ.
Πινακας 2: τα ιδια, ανα ΜΕΓΕΘΟΣ κοντρας πριν την εισοδο (απο τις 72ω, σε γκολ) — υπαρχει «καταστροφικο» κατωφλι; συνεχιζει η κοντρα;
Χαντικαπ: ολες οι σεζον 2022-26 (+ νεα μορφη)· συνολα: νεα μορφη 2024-26 (βαση live). ΠΕΡΙΓΡΑΦΙΚΟ. Εξοδος: ucl_late_picks_table_out.txt"""
import sys
import pandas as pd
sys.stdout.reconfigure(encoding='utf-8')
X = pd.read_pickle('ucl_bb_timing_alerts.pkl')
NEW = ['2425', '2526']
out = []
def P(s=''): print(s, flush=True); out.append(str(s))
def stats(d):
    if not len(d): return None
    g = d.groupby('bk'); ps = d.groupby('sea').pa.mean()
    return dict(n=g.size().mean(), ra=100 * g.pa.mean().mean(), rc=100 * g.pc.mean().mean(), ua=g.pa.sum().mean(),
                pos=f'{int((ps > 0).sum())}/{ps.size}', pre=d.mv.mean(), post=d.mv_after.mean(),
                cont=100 * (d.mv_after <= -0.05).mean(), back=100 * (d.mv_after >= 0.05).mean())
HDR = f'  {"":<22}{"picks":>6}{"ROI εισοδος":>13}{"ROI κλεισιμο":>14}{"μοναδες":>9}{"σεζον+":>8}{"κοντρα ΠΡΙΝ":>13}{"κινηση ΜΕΤΑ":>13}{"συνεχισε κοντρα":>17}{"γυρισε προς":>13}'
def row(lab, d):
    s = stats(d)
    if s is None:
        P(f'  {lab:<22}{"—":>6}'); return
    P(f'  {lab:<22}{s["n"]:>6.0f}{s["ra"]:>+12.1f}%{s["rc"]:>+13.1f}%{s["ua"]:>+9.1f}{s["pos"]:>8}{s["pre"]:>+13.2f}{s["post"]:>+13.2f}{s["cont"]:>16.0f}%{s["back"]:>12.0f}%')
HB = [('απο την αρχη (72ω)', None), ('48-72ω', (48, 72)), ('36-48ω', (36, 48)), ('24-36ω', (24, 36)), ('12-24ω', (12, 24)),
      ('8-12ω', (8, 12)), ('4-8ω', (4, 8)), ('2-4ω', (2, 4)), ('τελευταιο 2ωρο', (0, 2))]
MV = [('χωρις κοντρα (≥0)', (-0.001, 9)), ('μικρη 0-0.15', (-0.15, -0.001)), ('0.15-0.25', (-0.25, -0.15)),
      ('0.25-0.40', (-0.40, -0.25)), ('≥0.40', (-9, -0.40))]
NAME = dict(fav='ΦΑΒΟΡΙ (χαντικαπ)', dog='ΑΟΥΤΣΑΪΝΤΕΡ (χαντικαπ)', over='OVER', under='UNDER')
P('CHAMPIONS LEAGUE · PICKS ΑΝΑ ΩΡΑ ΠΡΩΤΗΣ ΕΜΦΑΝΙΣΗΣ & ΑΝΑ ΚΟΝΤΡΑ · μεσος Crown/SBOBET')
P('κοντρα ΠΡΙΝ = ποσο κινηθηκε η αγορα απο τις 72ω ως τη στιγμη που βγηκε το pick (γκολ, − = κοντρα)·')
P('κινηση ΜΕΤΑ = απο την εισοδο ως το κλεισιμο (− = η κοντρα συνεχισε)· «συνεχισε κοντρα» = % picks με ≥0.05 ακομα κοντρα ως το κλεισιμο')
for m, ss, sl in (('fav', None, 'ολες οι σεζον 2022-26'), ('fav', NEW, 'νεα μορφη 2024-26'),
                  ('dog', None, 'ολες οι σεζον 2022-26'), ('dog', NEW, 'νεα μορφη 2024-26'),
                  ('over', NEW, 'νεα μορφη 2024-26 (βαση live)'), ('under', NEW, 'νεα μορφη 2024-26 (βαση live)'),
                  ('under', None, 'ολες οι σεζον (πλαισιο)')):
    D = X[(X.mk == m) & (X.sea.isin(ss) if ss else True)]
    late = D[~D.at_open]
    P(''); P('=' * 130); P(f'{NAME[m]} · {sl}'); P('=' * 130)
    P(' 1) ΑΝΑ ΩΡΑ ΠΡΩΤΗΣ ΕΜΦΑΝΙΣΗΣ'); P(HDR)
    for lab, w in HB:
        row(lab, D[D.at_open] if w is None else late[(late.hrs >= w[0]) & (late.hrs < w[1])])
    P('  ' + '-' * 126)
    row('ΟΛΑ ΟΣΑ ΒΓΗΚΑΝ ΑΡΓΟΤΕΡΑ', late)
    row('ΟΛΑ', D)
    P(' 2) ΜΟΝΟ ΟΣΑ ΒΓΗΚΑΝ ΑΡΓΟΤΕΡΑ — ΑΝΑ ΚΟΝΤΡΑ ΠΡΙΝ ΤΗΝ ΕΙΣΟΔΟ'); P(HDR)
    for lab, (lo, hi) in MV:
        row(lab, late[(late.mv > lo) & (late.mv <= hi)])
    P('  ' + '-' * 126)
    row('κοντρα ≥0.25 (≥6ω πριν)', late[late.apply(lambda r: isinstance(r.hx, dict) and 0.25 in r.hx and r.hx[0.25] >= 6, axis=1)])
    row('κοντρα ≥0.25 (<6ω πριν)', late[late.apply(lambda r: isinstance(r.hx, dict) and 0.25 in r.hx and r.hx[0.25] < 6, axis=1)])
P(''); P('(σημ.) καθε γραμμη = μεσος 2 βιβλιων (picks ανα βιβλιο)· σεζον+ = σεζον με θετικο ROI στην εισοδο. Μικρα κελια (<10) = ενδεικτικα.')
open('ucl_late_picks_table_out.txt', 'w', encoding='utf-8').write('\n'.join(out))
